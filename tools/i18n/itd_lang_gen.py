#!/usr/bin/env python3
# itd_lang_gen.py: tools/i18n/itd_lang_data.py -> runtime/ui/itd_lang.h (Inside The Dream's start screen, 10 languages)
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from itd_lang_data import T
CODES = ["ja", "es", "de", "it", "nl", "ru", "ko", "zh-Hans", "zh-Hant", "pt-BR"]
def c(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + s + '"'
for k, v in T.items():
    assert len(v) == len(CODES), k
    for t in v:
        assert re.findall(r"%[sd]", t) == re.findall(r"%[sd]", k), (k, t)
out = ["// Inside The Dream's start screen in the languages of LAS Recomp Beta 6 besides English and French",
       "// (runtime/ui/launcher.mm itd_t / itd_tr; French is written there beside each English text).",
       "// GENERATED by tools/i18n/itd_lang_gen.py from tools/i18n/itd_lang_data.py - edit those, not this.",
       "#pragma once", "",
       "#define ITD_LANGS %d" % len(CODES),
       "static const char *const k_itd_lang_codes[ITD_LANGS] = {%s};" % ", ".join(c(x) for x in CODES),
       "// {English, then one per k_itd_lang_codes}; ends with a NULL English",
       "static const char *const k_itd_lang[][1 + ITD_LANGS] = {"]
for k, v in T.items():
    out.append("    {" + ", ".join(c(x) for x in (k,) + tuple(v)) + "},")
out += ["    {0},", "};", ""]
dst = os.path.join(here, "..", "..", "runtime", "ui", "itd_lang.h")
open(dst, "w", encoding="utf-8").write("\n".join(out))
print("wrote", os.path.normpath(dst), len(T), "texts")
