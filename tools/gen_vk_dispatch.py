#!/usr/bin/env python3
# tools/gen_vk_dispatch.py [vulkan include dir]: runtime/nvn/vulkan/vk_dispatch.{h,c} - every Vulkan command of
# vulkan_core.h and vulkan_android.h as a pointer (lr_vkX) the Android build of the backend calls through (vkX defined as
# lr_vkX, the header forced into each of its sources), loaded from the driver the headset app chose at start: the
# system's, or Mesa Turnip through libadrenotools (android/xr_app.c, LARECOMP_XR_TURNIP). The desktop builds don't use it.
import os, re, sys
inc = sys.argv[1] if len(sys.argv) > 1 else "/opt/homebrew/opt/vulkan-headers/include"
names = []
for hdr in ["vulkan/vulkan_core.h", "vulkan/vulkan_android.h"]:
    src = open(os.path.join(inc, hdr)).read()
    for m in re.finditer(r"VKAPI_ATTR\s+[\w\s\*]+?VKAPI_CALL\s+(vk\w+)\s*\(", src):
        if m.group(1) not in names:
            names.append(m.group(1))
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "runtime", "nvn", "vulkan")
h = ["// vk_dispatch.h - generated by tools/gen_vk_dispatch.py, do not edit: every Vulkan command as a pointer, loaded from",
     "// the driver chosen at start (android/xr_app.c: the system's, or Mesa Turnip through libadrenotools). Forced into each",
     "// source of runtime/nvn/vulkan in the Android build (android/prep/build_rt_android.sh). LR_VK_NO_MACROS: the",
     "// pointers and loaders only, vkX left as it is (android/xr_app.c keeps the system driver for its own device).",
     "#pragma once",
     "#if defined(__ANDROID__) && !defined(VK_USE_PLATFORM_ANDROID_KHR)",
     "#define VK_USE_PLATFORM_ANDROID_KHR",
     "#endif",
     "#include <vulkan/vulkan.h>",
     "#define LR_VK_DISPATCH 1",
     "#ifdef __cplusplus",
     'extern "C" {',
     "#endif"]
h += ["extern PFN_%s lr_%s;" % (n, n) for n in names]
h += ["void lr_vk_load_global(PFN_vkGetInstanceProcAddr gipa);  // before the instance: the loader's entry point",
      "void lr_vk_load_instance(VkInstance inst);                 // once the instance exists",
      "void lr_vk_load_device(VkDevice dev);                      // once the device exists (its own entry points)",
      "#ifdef __cplusplus",
      "}",
      "#endif",
      "#ifndef LR_VK_NO_MACROS"]
h += ["#define %s lr_%s" % (n, n) for n in names]
h += ["#endif", ""]
open(os.path.join(out, "vk_dispatch.h"), "w").write("\n".join(h))
c = ["// vk_dispatch.c - generated by tools/gen_vk_dispatch.py, do not edit (vk_dispatch.h says what it is).",
     "#ifdef __ANDROID__  // (the desktop builds call the loader directly; the header's Android types too)",
     "#define LR_VK_NO_MACROS",
     '#include "vk_dispatch.h"',
     ""]
c += ["PFN_%s lr_%s;" % (n, n) for n in names]
c += ["", "static const struct { const char *name; PFN_vkVoidFunction *fn; } k_fns[] = {"]
c += ['    {"%s", (PFN_vkVoidFunction *)&lr_%s},' % (n, n) for n in names]
c += ["};",
      "#define NFNS (sizeof k_fns / sizeof k_fns[0])",
      "void lr_vk_load_global(PFN_vkGetInstanceProcAddr gipa) {",
      "    for (unsigned i = 0; i < NFNS; i++) *k_fns[i].fn = gipa(VK_NULL_HANDLE, k_fns[i].name);",
      "    lr_vkGetInstanceProcAddr = gipa;",
      "}",
      "void lr_vk_load_instance(VkInstance inst) {",
      "    PFN_vkGetInstanceProcAddr gipa = lr_vkGetInstanceProcAddr;",
      "    for (unsigned i = 0; i < NFNS; i++) {",
      "        PFN_vkVoidFunction f = gipa(inst, k_fns[i].name);",
      "        if (f) *k_fns[i].fn = f;",
      "    }",
      "    lr_vkGetInstanceProcAddr = gipa;",
      "}",
      "void lr_vk_load_device(VkDevice dev) {",
      "    for (unsigned i = 0; i < NFNS; i++) {",
      "        PFN_vkVoidFunction f = lr_vkGetDeviceProcAddr(dev, k_fns[i].name);",
      "        if (f) *k_fns[i].fn = f;",
      "    }",
      "}",
      "#endif",
      ""]
open(os.path.join(out, "vk_dispatch.c"), "w").write("\n".join(c))
print("%d commands" % len(names))
