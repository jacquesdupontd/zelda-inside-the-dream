#!/usr/bin/env python3
"""Embed pinned, unmodified Qualcomm shaders with explicit Vulkan adaptations."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "third_party/sgsr2"
out = ["// Generated by tools/embed_sgsr2.py; original shaders and BSD license alongside.\n"]
for shader in ("convert", "upscale", "upscale_hq"):
    kind = shader.removesuffix("_hq")
    source = (root / f"sgsr2_{kind}.fs").read_text()
    source = source.replace("#version 320 es", "#version 450\n#define REQUEST_NDC_Y_UP 1")
    source = source.replace("layout(std140, set = 0, binding = 0) uniform readonly Params", "layout(push_constant) uniform Params")
    source = source.replace("layout(std140, set = 0, binding = 0) uniform Params", "layout(push_constant) uniform Params")
    source = source.replace("layout(location = 0) in highp vec2 texCoord;", "")
    if kind == "convert":
        source = source.replace("layout(set = 0, binding = 1)", "layout(set = 0, binding = 0)")
        source = source.replace("layout(set = 0, binding = 2) uniform mediump sampler2D InputVelocity;", "")
        source = source.replace("vec4 EncodedVelocity = texelFetch(InputVelocity, ivec2(InputPos), 0);", "vec4 EncodedVelocity = vec4(0.0); // camera motion only; no object-motion claim")
    else:
        # Separate shader variants keep the optional nine-tap code and its
        # register pressure out of the default five-tap GPU program.
        source = source.replace("if (false)  //maybe disable this for ultra performance, true could generate more realistic output",
                                "if (" + ("true" if shader.endswith("_hq") else "false") + ") // optional vendor nine-tap neighbourhood")
        for i in range(1, 4):
            source = source.replace(f"binding = {i})", f"binding = {i - 1})")
        # Signed Lanczos sums can be negative. Adding reset to the quotient
        # does not force alpha=1 in that case: camera cuts must override history.
        source = source.replace("float alpha = clamp(Upsampledcw.w / alphasum + params.reset, 0.0, 1.0);",
                                "float alpha = params.reset > 0.5 ? 1.0 : clamp(Upsampledcw.w / alphasum, 0.0, 1.0);")
        source = source.replace("Upsampledcw.xyz = mix(HistoryColor, Upsampledcw.xyz, alpha);",
                                "vec3 spatial = Upsampledcw.xyz;\n    Upsampledcw.xyz = mix(HistoryColor, spatial, alpha);")
        source = source.replace("Output = vec4(Upsampledcw.xyz, 0.0);",
                                "Output = vec4((params.bSameCamera & 2u) != 0u ? abs(Upsampledcw.xyz - spatial) * 8.0 : Upsampledcw.xyz, 0.0);")
        # texelFetch ignores the sampler's CLAMP_TO_EDGE mode. The 3x3
        # neighbourhood otherwise performs undefined reads at the image border.
        source = source.replace("texelFetch(InputColor,", "sgsr2Texel(InputColor,")
        helper = ("vec4 sgsr2Texel(sampler2D image, ivec2 pixel, int lod) {\n"
                  " return texelFetch(image, clamp(pixel, ivec2(0), textureSize(image,lod)-1), lod);\n}\n")
        source = source.replace("void main()", helper + "void main()")
    member = "renderSizeRcp" if kind == "convert" else "outputSizeRcp"
    source = source.replace("void main()", f"#define texCoord (gl_FragCoord.xy * params.{member})\nvoid main()")
    out.append(f"static const char sgsr2_{shader}_src[] =\n")
    out.extend(json.dumps(line + "\n") + "\n" for line in source.splitlines())
    out.append(";\n")
target = root / "shaders.inc"
content = "".join(out)
if not target.exists() or target.read_text() != content:
    target.write_text(content)
